# --------------------------------------------------
# SMARTVISION AI - IMAGE CLASSIFICATION
# --------------------------------------------------

# Import required libraries
import streamlit as st
import pandas as pd

# Import image processing function
from utils.image_processor import preprocess_image

# Import prediction function
from utils.prediction import predict_with_all_models


# --------------------------------------------------
# 1. PAGE CONFIGURATION
# --------------------------------------------------

st.set_page_config(
    page_title="Image Classification | SmartVision AI",
    layout="wide"
)


# --------------------------------------------------
# 2. PAGE HEADING
# --------------------------------------------------

st.title("Image Classification")

st.write(
    "Upload an image and compare predictions from "
    "four different deep learning models."
)

st.markdown("---")


# --------------------------------------------------
# 3. IMAGE UPLOAD SECTION
# --------------------------------------------------

st.subheader("Upload an Image")

uploaded_image = st.file_uploader(
    "Choose an image",
    type=["jpg", "jpeg", "png"],
    help="Upload an image containing one of the 25 supported classes."
)


# --------------------------------------------------
# 4. DISPLAY UPLOADED IMAGE
# --------------------------------------------------

if uploaded_image is not None:

    # Display image and project information in two columns
    col1, col2 = st.columns([1, 1])

    with col1:

        st.image(
            uploaded_image,
            caption="Uploaded Image",
            use_container_width=True
        )

        st.success("Image uploaded successfully!")

    with col2:

        st.info(
            "The uploaded image will be processed "
            "using four trained CNN models."
        )

        st.write("**Supported image classes:** 25")

        st.write("**Classification models:**")

        st.write("- VGG16")
        st.write("- ResNet50")
        st.write("- MobileNetV2")
        st.write("- EfficientNetB0")

    st.markdown("---")


    # --------------------------------------------------
    # 5. CLASSIFICATION BUTTON
    # --------------------------------------------------

    if st.button(
        "Start Classification",
        use_container_width=True
    ):

        try:

            # Step 1: Preprocess the uploaded image
            with st.spinner("Processing image..."):

                processed_image = preprocess_image(
                    uploaded_image
                )

            # Step 2: Generate predictions using all models
            with st.spinner(
                "Running predictions using all four models..."
            ):

                all_results = predict_with_all_models(
                    processed_image
                )

            # Save predictions in session state
            st.session_state["classification_results"] = all_results

            st.success("Classification completed successfully!")

        except Exception as error:

            st.error(
                f"An error occurred during classification: {error}"
            )


# --------------------------------------------------
# 6. DISPLAY CLASSIFICATION RESULTS
# --------------------------------------------------

if "classification_results" in st.session_state:

    all_results = st.session_state["classification_results"]

    st.markdown("---")

    st.header("Classification Results")

    # Create four columns for displaying model predictions
    columns = st.columns(4)

    # Display prediction and confidence for each model
    for column, (model_name, results) in zip(
        columns,
        all_results.items()
    ):

        with column:

            st.subheader(model_name)

            st.metric(
                label="Predicted Class",
                value=results["predicted_class"]
            )

            st.metric(
                label="Confidence",
                value=f'{results["confidence_percentage"]:.2f}%'
            )


    # --------------------------------------------------
    # 7. MODEL CONFIDENCE COMPARISON
    # --------------------------------------------------

    st.markdown("---")

    st.header("Model Confidence Comparison")

    st.write(
        "Compare the confidence scores generated by "
        "the four trained CNN models."
    )

    # Extract model names and confidence scores
    confidence_scores = {
        model_name: results["confidence_percentage"]
        for model_name, results in all_results.items()
    }

    # Convert the dictionary into a Pandas DataFrame
    confidence_df = pd.DataFrame(
        {
            "Model": list(confidence_scores.keys()),
            "Confidence (%)": list(confidence_scores.values())
        }
    )

    # Display bar chart
    st.subheader("Confidence Score by Model")

    chart_data = confidence_df.set_index("Model")

    st.bar_chart(
        chart_data,
        y="Confidence (%)"
    )

    # Find the model with the highest confidence
    best_model = max(
        confidence_scores,
        key=confidence_scores.get
    )

    best_confidence = confidence_scores[best_model]

    # Highlight the highest-confidence prediction
    st.success(
        f"Highest confidence: {best_model} "
        f"({best_confidence:.2f}%)"
    )

    # Display comparison table
    st.subheader("Model Comparison Table")

    st.dataframe(
        confidence_df.sort_values(
            by="Confidence (%)",
            ascending=False
        ),
        use_container_width=True,
        hide_index=True
    )


    # --------------------------------------------------
    # 8. TOP-5 PREDICTIONS
    # --------------------------------------------------

    st.markdown("---")

    st.header("Top-5 Predictions")

    # Display the top five predictions from each model
    for model_name, results in all_results.items():

        with st.expander(
            f"{model_name} - Top 5 Predictions"
        ):

            for prediction in results["top_predictions"]:

                class_name = prediction["class_name"]

                confidence = prediction["confidence_percentage"]

                # Display predicted class and confidence
                st.write(
                    f"**{class_name}** - {confidence:.2f}%"
                )

                # Display confidence using a progress bar
                st.progress(
                    min(max(confidence / 100, 0.0), 1.0)
                )


    # --------------------------------------------------
    # 9. CLASSIFICATION INFORMATION
    # --------------------------------------------------

    st.markdown("---")

    st.caption(
        "SmartVision AI | Image Classification using "
        "VGG16, ResNet50, MobileNetV2 and EfficientNetB0."
    )